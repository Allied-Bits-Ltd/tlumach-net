using System;
using System.ComponentModel;
using System.Diagnostics;
using System.Globalization;
using System.Threading;

using Tlumach.Base;

namespace Tlumach.WinUI
{
    /// <summary>
    /// <para>Represents a unit of translation - a unit of text (a word, a phrase, a sentence, etc.) in a translation accessible using a unique key.</para>
    /// <para>This class is used in the code generated for WinUI (and Uno Platform) applications. It implements <see cref="INotifyPropertyChanged"/>, so XAML bindings to <see cref="CurrentValue"/> update when the language changes.</para>
    /// </summary>
    [DebuggerDisplay("{DebuggerDisplay,nq}")]
    public class TranslationUnit : BaseTranslationUnit, INotifyPropertyChanged, IDisposable
    {
        private string? _currentValue;

        // The synchronization context of the UI thread. PropertyChanged is raised in this context because WinUI (and Uno Platform)
        // bindings must be updated on the UI thread. The context is captured when the unit is created or, if the unit was created
        // on some thread without a context (e.g., in a static initializer of the generated class), on the first read of CurrentValue,
        // which XAML bindings perform on the UI thread.
        private SynchronizationContext? _uiContext;

        /// <summary>
        /// Fires when the value of <see cref="CurrentValue"/> changes: when the text is retrieved on the first read of <see cref="CurrentValue"/>, and when the culture of the associated translation manager changes or <see cref="NotifyPlaceholdersUpdated"/> is called and the text becomes different.
        /// <para>The notifications of the changes are raised in the synchronization context of the thread that created the unit or, if there was none, of the thread that first read <see cref="CurrentValue"/> (normally, the UI thread).</para>
        /// </summary>
        public event PropertyChangedEventHandler? PropertyChanged;

        /// <summary>
        /// Initializes a new instance of the <see cref="TranslationUnit"/> class.
        /// <para>For internal use. This constructor is used by <seealso cref="UntranslatedUnit"/>.</para>
        /// </summary>
        /// <param name="translationManager">The translation manager to which the unit is bound.</param>
        /// <param name="translationConfiguration">The translation configuration used to create the unit.</param>
        /// <param name="containsPlaceholders">An indicator of whether the unit contains placeholders.</param>
        protected TranslationUnit(TranslationManager translationManager, TranslationConfiguration translationConfiguration, bool containsPlaceholders)
            : base(translationManager, translationConfiguration, containsPlaceholders)
        {
            _uiContext = SynchronizationContext.Current;

            if (TranslationManager != TranslationManager.Empty)
                TranslationManager.OnCultureChanged += TranslationManager_OnCultureChanged;
        }

        /// <summary>
        /// Initializes a new instance of the <see cref="TranslationUnit"/> class.
        /// <para>For internal use. This constructor is used by the code generated by Generator.</para>
        /// </summary>
        /// <param name="translationManager">The translation manager to which the unit is bound.</param>
        /// <param name="translationConfiguration">The translation configuration used to create the unit.</param>
        /// <param name="key">The key of the unit.</param>
        /// <param name="containsPlaceholders">An indicator of whether the unit contains placeholders.</param>
        public TranslationUnit(TranslationManager translationManager, TranslationConfiguration translationConfiguration, string key, bool containsPlaceholders)
            : base(translationManager, translationConfiguration, key, containsPlaceholders)
        {
            _uiContext = SynchronizationContext.Current;

            // Subscribe for culture changes
            TranslationManager.OnCultureChanged += TranslationManager_OnCultureChanged;
        }

        /// <summary>
        /// Gets the text of the unit for the current culture of the associated translation manager (or, if the unit is bound to <see cref="TranslationManager.Empty"/>, for <see cref="CultureInfo.CurrentCulture"/>).
        /// <para>The text is retrieved on the first read and then updated every time the culture of the translation manager changes or <see cref="NotifyPlaceholdersUpdated"/> is called.</para>
        /// </summary>
        public string CurrentValue
        {
            get
            {
                _uiContext ??= SynchronizationContext.Current;

                if (_currentValue is null)
                {
                    // Initial text
                    _currentValue = GetValue(TranslationManager == TranslationManager.Empty ? CultureInfo.CurrentCulture : TranslationManager.CurrentCulture);
                    PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(CurrentValue)));
                }

                return _currentValue;
            }

            private set
            {
                if (string.Equals(_currentValue, value, StringComparison.Ordinal))
                    return;

                _currentValue = value;
                NotifyCurrentValueChanged();
            }
        }

        private void NotifyCurrentValueChanged()
        {
            SynchronizationContext? uiContext = _uiContext;

            // The new value is stored immediately so that code reading CurrentValue sees it at once; only the notification
            // is posted to the UI thread, where the bindings read the (by then current) value.
            if (uiContext is null || ReferenceEquals(SynchronizationContext.Current, uiContext))
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(CurrentValue)));
            else
                uiContext.Post(static state => ((TranslationUnit)state!).RaiseCurrentValueChanged(), this);
        }

        private void RaiseCurrentValueChanged()
        {
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(CurrentValue)));
        }

        /// <summary>
        /// Returns the current text of the unit.
        /// </summary>
        /// <returns>The value of <see cref="CurrentValue"/>.</returns>
        public override string ToString() => CurrentValue ?? string.Empty;

        /// <summary>
        /// Converts the unit to its current text.
        /// </summary>
        /// <param name="unit">The unit to convert.</param>
        /// <returns>The current text of <paramref name="unit"/>, or an empty string if <paramref name="unit"/> is <see langword="null"/>.</returns>
        public static implicit operator string(TranslationUnit unit)
            => unit?.ToString() ?? string.Empty;

        private string DebuggerDisplay() => $"Translation unit '{Key}': '{CurrentValue ?? "(No value)"}'";

        /// <summary>
        /// Notifies XAML bindings that they need to request a new value and update the controls.
        /// </summary>
        public override void NotifyPlaceholdersUpdated()
        {
            CurrentValue = GetValue(TranslationManager.CurrentCulture);
        }

        private void TranslationManager_OnCultureChanged(object? sender, CultureChangedEventArgs args)
        {
            // Re-translate and notify
            CurrentValue = GetValue(args.Culture);
        }

        /// <summary>
        /// Releases the resources of the unit.
        /// </summary>
        /// <param name="disposing"><see langword="true"/> to unsubscribe the unit from the culture changes of the translation manager; <see langword="false"/> to do nothing.</param>
        protected virtual void Dispose(bool disposing)
        {
            if (disposing)
            {
                // Dispose managed resources.
#pragma warning disable S1066 // Mergeable "if" statements should be combined
                if (TranslationManager != TranslationManager.Empty)
                    TranslationManager.OnCultureChanged -= TranslationManager_OnCultureChanged;
#pragma warning restore S1066 // Mergeable "if" statements should be combined
            }
        }

        /// <summary>
        /// Unsubscribes the unit from the culture changes of the translation manager.
        /// </summary>
        public void Dispose()
        {
            Dispose(true);
            GC.SuppressFinalize(this);
        }
    }
}
