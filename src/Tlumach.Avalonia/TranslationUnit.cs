using System.Diagnostics;

using Tlumach.Base;

namespace Tlumach.Avalonia
{
    /// <summary>
    /// <para>Represents a unit of translation - a unit of text (a word, a phrase, a sentence, etc.) in a translation accessible using a unique key.</para>
    /// <para>This class is used in the code generated for Avalonia applications. It exposes the text as an observable (<see cref="Value"/>) that Avalonia bindings subscribe to.</para>
    /// </summary>
    [DebuggerDisplay("{DebuggerDisplay,nq}")]
    public class TranslationUnit : BaseTranslationUnit, IDisposable
    {
        private readonly ValueSubject _value;

        /// <summary>
        /// Gets an observable that sends the current text of the unit to each new subscriber and the new text to all subscribers every time the culture of the associated translation manager changes or <see cref="NotifyPlaceholdersUpdated"/> is called.
        /// <para>The new text may be sent on any thread; Avalonia bindings post it to the UI thread themselves.</para>
        /// </summary>
        public IObservable<string> Value => _value;

        /// <summary>
        /// Gets the current text of the unit, i.e., the text that <see cref="Value"/> has sent last.
        /// </summary>
        public string CurrentValue => _value.Value;

        /// <summary>
        /// Initializes a new instance of the <see cref="TranslationUnit"/> class.
        /// <para>For internal use. This constructor is used by <seealso cref="UntranslatedUnit"/>.</para>
        /// </summary>
        /// <param name="sourceValue">The initial value of the text.</param>
        /// <param name="translationManager">The translation manager to which the unit is bound.</param>
        /// <param name="translationConfiguration">The translation configuration used to create the unit.</param>
        /// <param name="containsPlaceholders">An indicator of whether the unit contains placeholders.</param>
        protected TranslationUnit(string sourceValue, TranslationManager translationManager, TranslationConfiguration translationConfiguration, bool containsPlaceholders)
            : base(translationManager, translationConfiguration, containsPlaceholders)
        {
            _value = new ValueSubject(sourceValue);

            if (TranslationManager != TranslationManager.Empty)
                TranslationManager.OnCultureChanged += TranslationManager_OnCultureChanged;
        }

        /// <summary>
        /// Initializes a new instance of the <see cref="TranslationUnit"/> class.
        /// <para>For internal use. This constructor is used by the code generated by Generator.</para>
        /// </summary>
        /// <param name="translationManager">The translation manager to which the unit is bound.</param>
        /// <param name="translationConfiguration">The translation configuration used to create the unit.</param>
        /// <param name="key">The key of the unit.</param>
        /// <param name="containsPlaceholders">An indicator of whether the unit contains placeholders.</param>
        public TranslationUnit(TranslationManager translationManager, TranslationConfiguration translationConfiguration, string key, bool containsPlaceholders)
            : base(translationManager, translationConfiguration, key, containsPlaceholders)
        {
            string value = GetValue(TranslationManager.CurrentCulture);
            _value = new ValueSubject(value);
            TranslationManager.OnCultureChanged += TranslationManager_OnCultureChanged;
        }

        /// <summary>
        /// Releases the resources of the unit.
        /// </summary>
        /// <param name="disposing"><see langword="true"/> to unsubscribe the unit from the culture changes of the translation manager and stop the <see cref="Value"/> observable, which then drops its subscribers and sends no more text; <see langword="false"/> to do nothing.</param>
        protected virtual void Dispose(bool disposing)
        {
            if (disposing)
            {
                // Dispose managed resources.
                if (TranslationManager != TranslationManager.Empty)
                    TranslationManager.OnCultureChanged -= TranslationManager_OnCultureChanged;
                _value.Dispose();
            }
        }

        /// <summary>
        /// Unsubscribes the unit from the culture changes of the translation manager and stops the <see cref="Value"/> observable, which then drops its subscribers and sends no more text.
        /// </summary>
        public void Dispose()
        {
            Dispose(true);
            GC.SuppressFinalize(this);
        }

        /// <summary>
        /// Returns the current text of the unit.
        /// </summary>
        /// <returns>The value of <see cref="CurrentValue"/>.</returns>
        public override string ToString() => CurrentValue ?? string.Empty;

        /// <summary>
        /// Converts the unit to its current text.
        /// </summary>
        /// <param name="unit">The unit to convert.</param>
        /// <returns>The current text of <paramref name="unit"/>, or an empty string if <paramref name="unit"/> is <see langword="null"/>.</returns>
        public static implicit operator string(TranslationUnit unit)
            => unit?.ToString() ?? string.Empty;

        private string DebuggerDisplay() => $"Translation unit '{Key}': '{CurrentValue ?? "(No value)"}'";

        /// <summary>
        /// Notifies XAML bindings that they need to request a new value and update the controls.
        /// </summary>
        public override void NotifyPlaceholdersUpdated()
        {
            _value.OnNext(GetValue(TranslationManager.CurrentCulture));
        }

        private void TranslationManager_OnCultureChanged(object? sender, CultureChangedEventArgs args)
        {
            // Update listeners with the string value obtained for the new culture.
            // This may happen on any thread: the bindings of Avalonia (11 and 12) post the values that an observable produces on another thread to the UI thread themselves.
            _value.OnNext(GetValue(args.Culture));
        }
    }
}
