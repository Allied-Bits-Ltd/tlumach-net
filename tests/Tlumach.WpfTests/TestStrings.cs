using System.Globalization;
using System.IO;
using System.Text;

using Tlumach.Base;

namespace Tlumach.WpfTests
{
    /// <summary>
    /// Stands in for a class generated by Tlumach Generator: the translation manager and the translation units are kept in static properties,
    /// so they live as long as the application, and XAML refers to the units with <c>{x:Static}</c>.
    /// <para>The translations (an English default file and a German file) are written to a temporary directory and loaded from the disk.</para>
    /// </summary>
    public static class TestStrings
    {
        private const string DefaultFile = "Strings.json";

        private const string DefaultJson = """
            {
                "greeting": "Hello",
                "farewell": "Goodbye",
                "named": "Hello, {name}"
            }
            """;

        private const string GermanJson = """
            {
                "greeting": "Hallo",
                "farewell": "Auf Wiedersehen",
                "named": "Hallo, {name}"
            }
            """;

        static TestStrings()
        {
            JsonParser.Use();

            string directory = Path.Combine(Path.GetTempPath(), "TlumachWpfTests", Path.GetRandomFileName());
            Directory.CreateDirectory(directory);
            File.WriteAllText(Path.Combine(directory, DefaultFile), DefaultJson, Encoding.UTF8);
            File.WriteAllText(Path.Combine(directory, "Strings_de.json"), GermanJson, Encoding.UTF8);

            Configuration = new TranslationConfiguration(assembly: null, DefaultFile, "en", TextFormat.DotNet)
            {
                DirectoryHint = directory,
            };

            TranslationManager = new TranslationManager(Configuration)
            {
                LoadFromDisk = true,
                TranslationsDirectory = directory,
                CurrentCulture = CultureInfo.InvariantCulture,
            };

            Greeting = new TranslationUnit(TranslationManager, Configuration, "greeting", containsPlaceholders: false);
            Farewell = new TranslationUnit(TranslationManager, Configuration, "farewell", containsPlaceholders: false);
            Named = new TranslationUnit(TranslationManager, Configuration, "named", containsPlaceholders: true);
            FarewellHolder = new UnitHolder(Farewell);
        }

        public static CultureInfo German { get; } = new("de");

        public static TranslationConfiguration Configuration { get; }

        public static TranslationManager TranslationManager { get; }

        public static TranslationUnit Greeting { get; }

        public static TranslationUnit Farewell { get; }

        public static TranslationUnit Named { get; }

        /// <summary>
        /// Gets a view model with <see cref="Farewell"/>, for bindings with an explicit source (<c>Source={x:Static ...}</c>).
        /// </summary>
        public static UnitHolder FarewellHolder { get; }

        /// <summary>
        /// Switches the manager back to the default translation, which the tests expect at their start.
        /// </summary>
        public static void Reset() => TranslationManager.CurrentCulture = CultureInfo.InvariantCulture;
    }
}
